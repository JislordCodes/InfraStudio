/**
 * Turns cut lines from the engine into drawing sheets: a scale chosen to fit an A3 page,
 * line weights by element class, overall dimensions, a north arrow, a scale bar and a title
 * block. A sheet is plain data, so the same sheet renders to an SVG preview and to a PDF.
 */
import type { CutSegment, ModelTable } from './types.ts';

export const SHEET_W = 420;
export const SHEET_H = 297;

export type DrawItem =
  | { t: 'line'; x1: number; y1: number; x2: number; y2: number; w: number; c?: string; dash?: boolean }
  | { t: 'text'; x: number; y: number; s: number; text: string; anchor?: 'start' | 'middle' | 'end'; bold?: boolean; c?: string };

export interface Sheet {
  number: string;
  title: string;
  scale: string;
  items: DrawItem[];
}

const SCALES = [20, 25, 50, 75, 100, 125, 150, 200, 250, 300, 400, 500, 750, 1000, 1250, 1500, 2000, 2500, 5000, 10000];

/** Line weight in mm by what was cut. */
function weight(cls: string): number {
  if (/^Ifc(Wall|Column|CurtainWall)$/.test(cls)) return 0.5;
  if (/^Ifc(Slab|Roof|Beam|Footing|Stair|StairFlight|Member|Plate)$/.test(cls)) return 0.3;
  if (/^Ifc(Door|Window|Railing|Covering|ShadingDevice)$/.test(cls)) return 0.18;
  return 0.1;
}

function dedupe(segs: CutSegment[]): CutSegment[] {
  const seen = new Set<string>();
  const out: CutSegment[] = [];
  const r = (n: number) => Math.round(n * 1000);
  for (const s of segs) {
    const a = `${r(s.x1)},${r(s.y1)}`;
    const b = `${r(s.x2)},${r(s.y2)}`;
    if (a === b) continue;
    const key = a < b ? `${a}|${b}` : `${b}|${a}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(s);
  }
  return out;
}

export interface LevelMark {
  name: string;
  elevation: number;
}

interface LayoutArgs {
  segments: CutSegment[];
  kind: 'plan' | 'section';
  title: string;
  project: string;
  number: string;
  /** names of the two cut-plane axes, for the dimension labels */
  levels?: LevelMark[];
  date?: string;
}

const NICE = [1, 2, 5, 10, 20, 25, 50, 100, 200, 500, 1000];

export function layoutSheet(args: LayoutArgs): Sheet {
  const segs = dedupe(args.segments);
  const items: DrawItem[] = [];

  // frame
  const border = 10;
  const titleH = 28;
  const rect = (x: number, y: number, w: number, h: number, lw: number) => {
    items.push({ t: 'line', x1: x, y1: y, x2: x + w, y2: y, w: lw });
    items.push({ t: 'line', x1: x + w, y1: y, x2: x + w, y2: y + h, w: lw });
    items.push({ t: 'line', x1: x + w, y1: y + h, x2: x, y2: y + h, w: lw });
    items.push({ t: 'line', x1: x, y1: y + h, x2: x, y2: y, w: lw });
  };
  rect(border, border, SHEET_W - 2 * border, SHEET_H - 2 * border, 0.7);

  // title block
  const tbY = SHEET_H - border - titleH;
  items.push({ t: 'line', x1: border, y1: tbY, x2: SHEET_W - border, y2: tbY, w: 0.5 });
  const cols = [border, 190, 290, 335, SHEET_W - border];
  for (let i = 1; i < cols.length - 1; i++) items.push({ t: 'line', x1: cols[i], y1: tbY, x2: cols[i], y2: SHEET_H - border, w: 0.35 });
  const cell = (i: number, label: string, value: string, big = false) => {
    items.push({ t: 'text', x: cols[i] + 3, y: tbY + 5, s: 6, text: label.toUpperCase(), c: '#666666' });
    items.push({ t: 'text', x: cols[i] + 3, y: tbY + (big ? 17 : 15), s: big ? 14 : 10, text: value, bold: big });
  };
  cell(0, 'Project', args.project || 'Untitled project');
  cell(1, 'Sheet', args.title, true);
  cell(2, 'Scale', '', false);
  cell(3, 'Sheet no.', args.number, true);
  items.push({ t: 'text', x: cols[3] + 3, y: SHEET_H - border - 3, s: 6, text: args.date ?? new Date().toISOString().slice(0, 10), c: '#666666' });
  items.push({ t: 'text', x: cols[0] + 3, y: SHEET_H - border - 3, s: 6, text: 'Generated by InfraStudio from the IFC model. Check before use.', c: '#666666' });

  if (!segs.length) {
    items.push({ t: 'text', x: SHEET_W / 2, y: SHEET_H / 2, s: 14, text: 'Nothing is cut at this height.', anchor: 'middle', c: '#888888' });
    return { number: args.number, title: args.title, scale: '', items };
  }

  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const s of segs) {
    minX = Math.min(minX, s.x1, s.x2); maxX = Math.max(maxX, s.x1, s.x2);
    minY = Math.min(minY, s.y1, s.y2); maxY = Math.max(maxY, s.y1, s.y2);
  }
  const extW = Math.max(maxX - minX, 0.01);
  const extH = Math.max(maxY - minY, 0.01);

  // drawing area, leaving room for dimensions on two sides and a title line underneath
  const pad = 22;
  const areaX = border + pad;
  const areaY = border + pad;
  const areaW = SHEET_W - 2 * border - 2 * pad - 14;
  const areaH = tbY - border - 2 * pad - 14;
  let den = SCALES[SCALES.length - 1];
  for (const d of SCALES) {
    if ((extW * 1000) / d <= areaW && (extH * 1000) / d <= areaH) { den = d; break; }
  }
  const k = 1000 / den; // sheet millimetres per model metre
  const drawW = extW * k;
  const drawH = extH * k;
  const ox = areaX + (areaW - drawW) / 2;
  const oy = areaY + (areaH - drawH) / 2;
  const X = (x: number) => ox + (x - minX) * k;
  const Y = (y: number) => oy + drawH - (y - minY) * k; // north / up is up the page

  // light lines first so heavy ones sit on top
  const ordered = [...segs].sort((a, b) => weight(a.cls) - weight(b.cls));
  for (const s of ordered) {
    items.push({ t: 'line', x1: X(s.x1), y1: Y(s.y1), x2: X(s.x2), y2: Y(s.y2), w: weight(s.cls) });
  }

  // dimensions
  const tick = (x: number, y: number) => items.push({ t: 'line', x1: x - 1.2, y1: y + 1.2, x2: x + 1.2, y2: y - 1.2, w: 0.25 });
  const dimY = oy + drawH + 9;
  items.push({ t: 'line', x1: ox, y1: oy + drawH + 3, x2: ox, y2: dimY + 2, w: 0.15 });
  items.push({ t: 'line', x1: ox + drawW, y1: oy + drawH + 3, x2: ox + drawW, y2: dimY + 2, w: 0.15 });
  items.push({ t: 'line', x1: ox, y1: dimY, x2: ox + drawW, y2: dimY, w: 0.25 });
  tick(ox, dimY); tick(ox + drawW, dimY);
  items.push({ t: 'text', x: ox + drawW / 2, y: dimY - 1.5, s: 8, text: `${extW.toFixed(2)} m`, anchor: 'middle' });
  const dimX = ox + drawW + 9;
  items.push({ t: 'line', x1: ox + drawW + 3, y1: oy, x2: dimX + 2, y2: oy, w: 0.15 });
  items.push({ t: 'line', x1: ox + drawW + 3, y1: oy + drawH, x2: dimX + 2, y2: oy + drawH, w: 0.15 });
  items.push({ t: 'line', x1: dimX, y1: oy, x2: dimX, y2: oy + drawH, w: 0.25 });
  tick(dimX, oy); tick(dimX, oy + drawH);
  items.push({ t: 'text', x: dimX + 4, y: oy + drawH / 2, s: 8, text: `${extH.toFixed(2)} m`, anchor: 'start' });

  // level markers on sections
  if (args.kind === 'section' && args.levels) {
    for (const lv of args.levels) {
      if (lv.elevation < minY - 0.01 || lv.elevation > maxY + 0.01) continue;
      const y = Y(lv.elevation);
      for (let x = ox - 12; x < ox + drawW + 6; x += 6) items.push({ t: 'line', x1: x, y1: y, x2: Math.min(x + 3, ox + drawW + 6), y2: y, w: 0.12, c: '#888888' });
      items.push({ t: 'text', x: ox - 14, y: y - 1, s: 6, text: `${lv.name}  ${lv.elevation.toFixed(2)}`, anchor: 'end', c: '#444444' });
    }
  }

  // north arrow on plans
  if (args.kind === 'plan') {
    const nx = SHEET_W - border - 22;
    const ny = border + 26;
    items.push({ t: 'line', x1: nx, y1: ny, x2: nx, y2: ny - 14, w: 0.4 });
    items.push({ t: 'line', x1: nx, y1: ny - 14, x2: nx - 2.5, y2: ny - 8, w: 0.4 });
    items.push({ t: 'line', x1: nx, y1: ny - 14, x2: nx + 2.5, y2: ny - 8, w: 0.4 });
    items.push({ t: 'text', x: nx, y: ny - 16, s: 9, text: 'N', anchor: 'middle', bold: true });
  }

  // scale bar
  const target = (areaW * 0.25) / k;
  const barM = [...NICE].reverse().find((n) => n <= target) ?? 1;
  const bx = areaX;
  const by = tbY - 8;
  items.push({ t: 'line', x1: bx, y1: by, x2: bx + barM * k, y2: by, w: 0.5 });
  items.push({ t: 'line', x1: bx, y1: by - 1.5, x2: bx, y2: by + 1.5, w: 0.3 });
  items.push({ t: 'line', x1: bx + barM * k, y1: by - 1.5, x2: bx + barM * k, y2: by + 1.5, w: 0.3 });
  items.push({ t: 'text', x: bx + (barM * k) / 2, y: by - 2.5, s: 6, text: `${barM} m`, anchor: 'middle' });

  const scaleText = `1:${den}`;
  items.push({ t: 'text', x: cols[2] + 3, y: tbY + 17, s: 14, text: scaleText, bold: true });
  return { number: args.number, title: args.title, scale: scaleText, items };
}

/** Distinct levels to draw as plans, lowest first. Levels within 30 cm of each other are one plan. */
export function planLevels(table: ModelTable, max = 8): { names: string[]; elevation: number }[] {
  const sorted = [...table.storeys].sort((a, b) => a.elevation - b.elevation);
  const groups: { names: string[]; elevation: number }[] = [];
  for (const s of sorted) {
    const last = groups[groups.length - 1];
    if (last && Math.abs(last.elevation - s.elevation) < 0.3) last.names.push(s.name);
    else groups.push({ names: [s.name], elevation: s.elevation });
  }
  if (!groups.length && table.bbox) groups.push({ names: ['Ground'], elevation: table.bbox[2] });
  return groups.slice(0, max);
}

