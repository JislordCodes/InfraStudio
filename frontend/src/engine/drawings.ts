const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const PT = 0.3528;

export function sheetToSvg(sheet: Sheet): string {
  const parts: string[] = [`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SHEET_W} ${SHEET_H}" width="100%" style="background:#fff">`];
  parts.push(`<rect width="${SHEET_W}" height="${SHEET_H}" fill="#ffffff"/>`);
  parts.push('<g stroke-linecap="butt" fill="none">');
  for (const it of sheet.items) {
    if (it.t === 'line') {
      parts.push(`<line x1="${it.x1.toFixed(2)}" y1="${it.y1.toFixed(2)}" x2="${it.x2.toFixed(2)}" y2="${it.y2.toFixed(2)}" stroke="${it.c ?? '#111111'}" stroke-width="${it.w}"${it.dash ? ' stroke-dasharray="2 1.5"' : ''}/>`);
    }
  }
  parts.push('</g>');
  for (const it of sheet.items) {
    if (it.t === 'text' && it.text) {
      parts.push(`<text x="${it.x.toFixed(2)}" y="${it.y.toFixed(2)}" font-family="Helvetica, Arial, sans-serif" font-size="${(it.s * PT).toFixed(2)}" font-weight="${it.bold ? 700 : 400}" fill="${it.c ?? '#111111'}" text-anchor="${it.anchor ?? 'start'}">${esc(it.text)}</text>`);
    }
  }
  parts.push('</svg>');
  return parts.join('');
}

function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

/** One A3 landscape PDF, one page per sheet. */
export async function sheetsToPdf(sheets: Sheet[]): Promise<Blob> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a3' });
  sheets.forEach((sheet, i) => {
    if (i > 0) doc.addPage('a3', 'landscape');
    for (const it of sheet.items) {
      if (it.t === 'line') {
        const [r, g, b] = hexToRgb(it.c ?? '#111111');
        doc.setDrawColor(r, g, b);
        doc.setLineWidth(it.w);
        doc.line(it.x1, it.y1, it.x2, it.y2);
      }
    }
    for (const it of sheet.items) {
      if (it.t === 'text' && it.text) {
        const [r, g, b] = hexToRgb(it.c ?? '#111111');
        doc.setTextColor(r, g, b);
        doc.setFont('helvetica', it.bold ? 'bold' : 'normal');
        doc.setFontSize(it.s);
        doc.text(it.text, it.x, it.y, { align: it.anchor === 'middle' ? 'center' : it.anchor === 'end' ? 'right' : 'left' });
      }
    }
  });
  return doc.output('blob');
}
